"""Deterministic learning-asset catalog for the Learning Path chain.

This module is pure static data plus pure lookup logic:

- it never calls any LLM/AI API and introduces no external dependency;
- it never changes Matching, Gap Analysis, What-if deltas, Minimal Action
  Sets, route selection, ordering, dependencies, gains or costs;
- it only upgrades already-planned actions into concrete learning content
  (title / deliverable / acceptance criteria) and keeps the existing planner
  templates as the fallback whenever an asset is not configured, so every
  skill can still generate a path;
- every lookup is deterministic (normalized keys, no randomness).

Cost-model priority: ``estimated_hours`` produced by ``LearningRoutePlanner``
is always authoritative.  The optional ``estimated_hours`` stored here is
reference metadata only and is never applied over the planner cost model.
"""

from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass


@dataclass(frozen=True)
class LearningAsset:
    """One concrete learning asset for a skill at a specific stage."""

    skill_ids: tuple[str, ...]
    names: tuple[str, ...]
    stage: str
    title: str
    deliverable: str
    acceptance_criteria: tuple[str, ...]
    estimated_hours: float | None = None
    resource_keywords: tuple[str, ...] = ()
    target_levels: tuple[str, ...] = ()


@dataclass(frozen=True)
class ResponsibilityActionTemplate:
    """Responsibility practice template used by the route planner."""

    name: str
    patterns: tuple[str, ...]
    deliverable: str
    acceptance_criteria: tuple[str, ...]
    base_hours: float


