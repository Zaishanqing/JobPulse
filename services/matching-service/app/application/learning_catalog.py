_STAGE_CRITERIA = {
    "foundation": ("基础练习可复现", "覆盖核心知识点并保留练习记录", "能说明关键概念与运行结果"),
    "proficiency": ("达到目标等级的能力评估", "在任务或练习中演示通过", "产出可核验记录"),
    "project": ("交付物完整且可运行", "验收标准明确", "形成指标记录与复盘说明"),
    "ownership": ("独立负责范围可核验", "交付物可运行且可维护", "成果与影响可溯源"),
}


def _stage_assets(
    skill_ids: tuple[str, ...],
    names: tuple[str, ...],
    foundation: tuple[str, str],
    proficiency: tuple[str, str],
    project: tuple[str, str],
    ownership: tuple[str, str],
    keywords: tuple[str, ...],
) -> tuple[LearningAsset, ...]:
    """Expand one skill spec into the four standard learning stages."""
    stages = (
        ("foundation", 8.0, foundation, ("basic", "unknown")),
        ("proficiency", 12.0, proficiency, ("working", "proficient")),
        ("project", 24.0, project, ()),
        ("ownership", 32.0, ownership, ()),
    )
    return tuple(
        LearningAsset(
            skill_ids=skill_ids,
            names=names,
            stage=stage,
            title=title,
            deliverable=deliverable,
            acceptance_criteria=_STAGE_CRITERIA[stage],
            estimated_hours=hours,
            resource_keywords=keywords,
            target_levels=target_levels,
        )
        for stage, hours, (title, deliverable), target_levels in stages
    )


