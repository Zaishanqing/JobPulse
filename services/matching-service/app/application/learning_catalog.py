def responsibility_action_template(text: str) -> ResponsibilityActionTemplate:
    lowered = text.casefold()
    for template in RESPONSIBILITY_ACTION_TEMPLATES:
        if any(pattern in lowered for pattern in template.patterns):
            return template
    concise = re.split(r"[，,；;。]", text, maxsplit=1)[0].strip()
    concise = re.sub(r"^(?:负责|参与|主导|承担|协助)", "", concise).strip()
    name = f"{concise[:32]}综合实践" if concise else "岗位职责综合实践"
    return ResponsibilityActionTemplate(
        name,
        (),
        f"围绕“{text}”完成一项可运行或可复现的实践交付物，并形成指标记录和复盘说明",
        ("交付物可运行或可复现", "记录输入、过程、结果和关键指标", "形成与岗位职责对应的证据说明"),
        16.0,
    )


