def _normalize(value: str | None) -> str:
    return unicodedata.normalize("NFKC", value or "").strip().casefold()


def _build_index() -> tuple[
    dict[str, tuple[LearningAsset, ...]],
    dict[str, tuple[LearningAsset, ...]],
]:
    by_skill: dict[str, list[LearningAsset]] = {}
    by_name: dict[str, list[LearningAsset]] = {}
    for asset in _LEARNING_ASSETS:
        for alias in asset.skill_ids:
            by_skill.setdefault(_normalize(alias), []).append(asset)
        for alias in asset.names:
            by_name.setdefault(_normalize(alias), []).append(asset)
    return (
        {key: tuple(items) for key, items in by_skill.items()},
        {key: tuple(items) for key, items in by_name.items()},
    )


_SKILL_INDEX, _NAME_INDEX = _build_index()


def _stage_matches(asset: LearningAsset, stage: str, target_level: str | None) -> bool:
    if asset.stage != stage:
        return False
    if asset.target_levels and target_level is not None:
        normalized_level = _normalize(target_level)
        if normalized_level not in {_normalize(item) for item in asset.target_levels}:
            return False
    return True


def lookup_learning_asset(
    *,
    skill_id: str | None,
    canonical_name: str | None = None,
    stage: str | None,
    target_level: str | None = None,
) -> LearningAsset | None:
    """Return the deterministic learning asset for a planned action, if any.

    Matching first tries the raw ``skill_id`` aliases, then the canonical skill
    name aliases.  A configured asset must also match the action stage; a
    configured ``target_levels`` restriction is only enforced when the action
    actually carries a target level.  Misses return ``None`` so the existing
    planner templates remain the fallback.
    """
    if stage is None:
        return None
    candidates = _SKILL_INDEX.get(_normalize(skill_id), ()) if skill_id else ()
    if not candidates and canonical_name:
        candidates = _NAME_INDEX.get(_normalize(canonical_name), ())
    for asset in candidates:
        if _stage_matches(asset, stage, target_level):
            return asset
    return None
